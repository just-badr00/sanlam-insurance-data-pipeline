"""Create a repeatable, incrementally changing insurance source system in Oracle.

Run `python seed_insurance_oracle.py --help` for options. All generated PII is fake.
"""
from __future__ import annotations

import argparse
import random
import sys
from datetime import datetime, timedelta, timezone
from decimal import Decimal

import oracledb
from faker import Faker

from oracle_db_connection import get_oracle_connection


TABLES = [
    "CLAIM_PAYMENTS", "CLAIMS", "PREMIUM_TRANSACTIONS", "POLICY_STATUS_HISTORY",
    "POLICY_COVERAGES", "POLICIES", "INSURANCE_PRODUCTS", "AGENTS", "CUSTOMERS",
]

